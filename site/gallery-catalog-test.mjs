import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {prepareModels,readGalleryQuery,galleryURL,emptyFacets} from './gallery/catalog-source.js';
import {filterItems} from './gallery/state.js';
import {catalogMembership} from './curation.js';
import {MEASURED_SUPPORTS,measuredSupport} from './gallery/model-support.js';
const manifest=JSON.parse(await readFile('assets/manifest.json'));
const resources=JSON.parse(await readFile('site/public/gallery/resources.json'));
const full={...manifest,assets:manifest.assets.map(a=>({...a,...catalogMembership(a)}))};
const models=prepareModels(full,resources);
assert.equal(models.length,manifest.assets.length);
assert(models.length>100,'Exercise more than one CatalogStore search page and prototype30');
assert.deepEqual(new Set(models.map(a=>a.id)),new Set(manifest.assets.map(a=>a.id)));
for(const model of models){assert.equal(model.glb,manifest.assets.find(a=>a.id===model.id).glb);assert(model.dimensions);assert(model.sha256.glb);assert(model.source_url);assert(model.blend);}
const extended=prepareModels({...full,assets:[...full.assets,{...full.assets.at(-1),id:'future-model'}]},resources);
assert.equal(extended.length,models.length+1,'Future catalog members are not truncated to a fixture size');
assert(extended.find(a=>a.id==='future-model'));
const unreviewed=models.find(a=>!resources.posters[a.id]);
if(unreviewed)assert.equal(unreviewed.galleryPosters,undefined);
const first=manifest.assets[0],mismatch={posters:{[first.id]:{...resources.posters[first.id],source_glb_sha256:'wrong'}}};
assert.equal(prepareModels({...full,assets:[first]},mismatch)[0].galleryPosters,undefined,'Stale images never get paired to new model bytes');
assert.throws(()=>prepareModels({...full,review_only:true},resources));
assert.equal(prepareModels({...full,review_only:true},resources,{allowReview:true}).length,models.length,'Explicit isolated review renderer does not change publication eligibility');
assert.throws(()=>prepareModels({...full,assets:[first,first]},resources));
assert.throws(()=>prepareModels({...full,assets:[{...first,glb:'https://other.test/private.glb'}]},resources));
const last=models.at(-1);assert(filterItems(models,last.id).some(a=>a.id===last.id),'Search reaches final published model');
assert.equal(filterItems([{id:'sample',name:{en:'Quartz Prism',zh:'石英'},category:'geology'}],'ＱＵＡＲＴＺ prism').length,1,'NFKC and multi-term matching');
assert.equal(filterItems([{id:'a',name:{en:'A'},triangles:5000}], '', {triangleMax:['5000']}).length,1);
assert.equal(filterItems([{id:'a',name:{en:'A'},triangles:5001}], '', {triangleMax:['5000']}).length,0);
const parsed=readGalleryQuery(new URLSearchParams('q=stone&world=prehistoric&pack=a&pack=b&category=geology&maxTriangles=5000&sort=triangles-desc'));
assert.deepEqual(parsed.facets.packs,['a','b']);assert.deepEqual(parsed.facets.triangleMax,['5000']);
const state={...parsed,lang:'zh',page:2,selected:last.id};
const url=galleryURL(state,{base:'/lowpoly-vault/',origin:'https://s010s.github.io'});
assert.equal(url.pathname,'/lowpoly-vault/zh-CN/models/page/3/');
assert.deepEqual(readGalleryQuery(url.searchParams),parsed,'All shareable filters survive reload and locale switch');
assert.deepEqual(emptyFacets(),{worlds:[],packs:[],category:[],collection:[],triangleBand:[],triangleMax:[]});
const bird=models.find(a=>a.id==='confuciusornis'),rule=MEASURED_SUPPORTS.confuciusornis;
assert.equal(bird.sha256.glb,rule.sha256,'Production must retain reviewed support source digest');
assert.equal(measuredSupport({...bird,sha256:{glb:'wrong'}},{sha256:rule.sha256}),null);
console.log(`Gallery catalog passed: ${models.length} real published models, future catalog growth, exact metadata, source-bound resources, full search/filter URLs and bilingual pagination.`);
