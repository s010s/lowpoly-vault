import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {projectedHeadingBounds,reviewedHeadingProfile} from '../detail-heading-policy.js';
const root=new URL('../../../',import.meta.url);
const assets=JSON.parse(readFileSync(new URL('assets/manifest.json',root))).assets;
const a=assets.find(a=>a.id==='spyroceras'),p=reviewedHeadingProfile(a);
assert.ok(p);
assert.equal(p.glb,'2a08b6e6d97ef9b5c7fe36cbdb49c335afbd772d2e503b3bd56d54cfe73b2a54');
assert.equal(p.preview,a.sha256.preview);
const pins=JSON.parse(readFileSync(new URL('site/public/gallery/resources.json',root))).files;
assert.equal(pins.find(x=>x.path===p.detail)?.sha256,p.preview);
assert.equal(reviewedHeadingProfile({...a,sha256:{...a.sha256,glb:'changed'}}),null);
assert.equal(reviewedHeadingProfile({...a,galleryPosters:{...a.galleryPosters,detail:'changed.png'}}),null);
assert.equal(reviewedHeadingProfile({...a,id:'karst-sinkhole'}),null);
const box=projectedHeadingBounds({left:407.515625,top:62,width:1032.484375,height:938},p.bounds);
for(const [key,value] of Object.entries({left:775.5844868606742,right:942.696436998718,top:114.65528335435874,bottom:864.6094465547698}))assert.ok(Math.abs(box[key]-value)<.001,key);
assert.equal(p.mobileTools,undefined);
assert.equal(p.mobileOnly,undefined);
console.log('Spyroceras exact version, poster index, negative gates and canonical vertex bounds pass');
