import assert from 'node:assert/strict';
import { startHandoffDissolve, HANDOFF_DISSOLVE_MS } from './handoff-dissolve.js';
let clock = 0, sequence = 0, finishes = 0;
const frames = new Map();
globalThis.performance = { now: () => clock };
globalThis.requestAnimationFrame = fn => { frames.set(++sequence, fn); return sequence; };
globalThis.cancelAnimationFrame = id => frames.delete(id);
const doc = new EventTarget(); doc.hidden = false;
const reduced = new EventTarget(); reduced.matches = false;
const node = () => ({ ownerDocument: doc, style: { opacity: '' }, isConnected: true });
const visual = node(), target = node();
const start = () => startHandoffDissolve({ visual, target, reduced, onFinish: () => finishes++ });
const flush = dt => { clock += dt; const pending = [...frames.values()]; frames.clear(); pending.forEach(fn => fn(clock)); };
const pair = () => [Number(visual.style.opacity), Number(target.style.opacity)];
const first = start();
assert.deepEqual(pair(), [1, 0]);
flush(1000);
assert.deepEqual(pair(), [.5, .5], 'Even a 1000ms first frame must retain a real partial blend');
assert.equal(finishes, 0, 'Do not retire the handoff in the same task as the first partial paint');
flush(16);
assert.equal(finishes, 1);
assert.equal(frames.size, 0, 'After a partial render opportunity, catch up without an accumulated delay');
assert.deepEqual([visual.style.opacity, target.style.opacity], ['', '']);
first.cancel(); assert.equal(finishes, 1);

const cancelled = start(); flush(25); assert.equal(pair()[0] + pair()[1], 1);
cancelled.cancel(); flush(1000); assert.equal(finishes, 1); assert.equal(frames.size, 0);
assert.deepEqual([visual.style.opacity, target.style.opacity], ['', ''], 'Cancellation restores the reusable original target opacity');

start(); flush(16); flush(150);
assert.equal(finishes, 2, 'A later slow frame catches the original deadline once a partial was presented');
start(); reduced.matches = true; reduced.dispatchEvent(new Event('change'));
assert.equal(finishes, 3); assert.equal(frames.size, 0);
reduced.matches = false;
start(); doc.hidden = true; doc.dispatchEvent(new Event('visibilitychange'));
assert.equal(finishes, 4); assert.equal(frames.size, 0);
doc.hidden = false;
start(); target.isConnected = false; flush(HANDOFF_DISSOLVE_MS);
assert.equal(finishes, 4, 'A stale detached owner cannot finish into a new view');
assert.equal(frames.size, 0); target.isConnected = true;
start(); for (let i = 0; i < 10; i++) flush(16);
assert.equal(finishes, 5, 'Healthy scheduling still completes at the 160ms nominal deadline');
assert.equal(frames.size, 0);
console.log('Handoff dissolve: complementary weights, first slow frame, wall-clock catchup, cancellation, reduced motion, visibility and stale ownership passed.');
