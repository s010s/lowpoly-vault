flush(1000);assert(Number(motion.canvas.dataset.revealWeight)<1);flush(1000);
assert.equal(finishes,1);assert.equal(frames.size,0);assert.equal(model.width,0);assert(motion.canvas.removed);
motion.cancel();assert.equal(finishes,1);
const cancelled=startHoverReveal({host,poster,model:canvas(),onFinish:()=>finishes++});cancelled.cancel();flush(HOVER_REVEAL_MS);assert.equal(finishes,1);assert.equal(frames.size,0);
console.log('Hover reveal: complementary alpha weights, finite timing, slow-frame progression and cancellation passed.');
