import assert from 'node:assert/strict';
import { startHoverReveal, paintHoverReveal, HOVER_REVEAL_MS } from './hover-reveal.js';
let clock=0,id=0;const frames=new Map(),draws=[];
const ctx={clearRect(){},drawImage(source){draws.push({source,alpha:this.globalAlpha,operation:this.globalCompositeOperation});}};
const canvas=()=>({width:320,height:320,dataset:{},getContext:()=>ctx,setAttribute(){},remove(){this.removed=true;}});
